"""PBR pack baking (v1.13, M12): bake each object material's node
recipe into texture maps in the job's output/ folder.

The pack per part: colour, roughness, normal, height, and metallic
where the family uses it. Baking runs in Blender (Cycles, 1 sample,
CPU - baking is deterministic at 1 sample) through a script
generated by blender_export.generate_bake_script: one material at a
time, one map at a time, one image in memory at a time. Metallic is
always a constant per part (the recipe sets it as a Principled
default_value, never a link), so the metallic map is a flat
grayscale PNG written host-side, not a Blender pass.

Glass never bakes: its look comes from transmission, not from
surface maps, so a pack would be a lie. It is recorded as a named
gap with the reason, in the bake report. String materials have no
recipe to bake, and imported meshes carry their own materials.

Bake resolution is capped at 1024 (no 8K - his PC). The resolution
comes from the build's material tier (Draft 256, Balanced 512,
Final 1024) unless the caller names one.
"""
from __future__ import annotations

import json
import struct
import zlib
from pathlib import Path

from . import blender_export, governor
from .jobs import Job

MAP_NAMES = ("color", "roughness", "normal", "height", "metallic")
VALID_RESOLUTIONS = (256, 512, 1024)

GLASS_SKIP_REASON = (
    "glass is transmissive - its look comes from light passing "
    "through it, not from surface maps, so there is nothing honest "
    "to bake")
IMPORTED_SKIP_REASON = (
    "imported meshes carry their own materials - only built parts bake")


def bake_map_name(slug: str, part_id: str, map_name: str) -> str:
    """The file name for one baked map."""
    return f"{slug}-{part_id}-{map_name}.png"


def bakeable_parts(desc: dict) -> tuple[list[dict], list[dict]]:
    """Split a description's parts into bakeable and skipped.

    Bakeable: {id, maps, metallic} - maps is the Blender-baked set
    (colour, roughness, normal, height), metallic is the style's
    constant metallic value (0.0 when the family has none). Skipped:
    {id, reason} - glass and imported parts, named with the reason.
    String-material parts are neither: they have no recipe, so they
    are not listed at all."""
    from . import materials as materials_mod

    bakeable: list[dict] = []
    skipped: list[dict] = []
    for part in desc.get("parts", []):
        material = part.get("material")
        if not isinstance(material, dict):
            continue
        if part.get("type") == "imported":
            skipped.append({"id": part["id"],
                            "reason": IMPORTED_SKIP_REASON})
            continue
        if material.get("family") == "glass":
            skipped.append({"id": part["id"],
                            "reason": GLASS_SKIP_REASON})
            continue
        resolved = materials_mod.resolve_spec(material)
        maps = ["color", "roughness", "normal"]
        if materials_mod.has_bump(material):
            maps.append("height")
        bakeable.append({"id": part["id"], "maps": maps,
                         "metallic": resolved["metallic"]})
    return bakeable, skipped


def _png_chunk(kind: bytes, data: bytes) -> bytes:
    return (struct.pack(">I", len(data)) + kind + data
            + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF))


def write_flat_png(path, size: int, gray: int) -> None:
    """A flat grayscale PNG, written with the stdlib only: one gray
    value for every pixel. Used for metallic maps, which are always
    a constant per part."""
    gray = max(0, min(255, int(round(gray))))
    ihdr = struct.pack(">IIBBBBB", size, size, 8, 0, 0, 0, 0)
    row = b"\x00" + bytes([gray]) * size
    png = (b"\x89PNG\r\n\x1a\n"
           + _png_chunk(b"IHDR", ihdr)
           + _png_chunk(b"IDAT", zlib.compress(row * size))
           + _png_chunk(b"IEND", b""))
    Path(path).write_bytes(png)


def bake_job(job: Job, workspace: Path, resolution: int | None = None,
             cancel=None, progress=None, exe=None,
             timeout: int = 1200) -> dict:
    """Bake one job's PBR packs into its output/ folder.

    Requires a built job (the .blend must exist). Returns a result
    dict: {"ok": True, "maps": [...], "skipped": [...],
    "resolution": N, "tier": ...} on success, {"ok": False,
    "problems": [...]} on a plain refusal. A governor refusal is a
    result, not an exception; a cancellation raises
    governor.Cancelled like a build. `progress`, when given, is
    called with (fraction, detail) as maps land."""
    from . import materials as materials_mod
    from . import settings as settings_mod

    desc = job.load_description()
    slug = job.dir.name
    bakeable, skipped = bakeable_parts(desc)
    if not bakeable:
        if skipped:
            names = ", ".join(s["id"] for s in skipped)
            problem = ("nothing in this job can be baked: " + names
                       + " cannot bake - " + skipped[0]["reason"]
                       + (" (and the other parts have no material "
                          "recipe)" if len(skipped) > 1 else ""))
        else:
            problem = ("nothing in this job can be baked: no part has "
                       "an object material - plain colours and glass "
                       "have no recipe to bake")
        return {"ok": False, "problems": [problem]}
    tier = settings_mod.resolve_render_settings(workspace, desc)["tier"]
    if resolution is None:
        resolution = materials_mod.bake_resolution(tier)
    elif resolution not in VALID_RESOLUTIONS:
        raise ValueError(
            f"bake resolution must be one of {VALID_RESOLUTIONS}, "
            f"got {resolution!r}")
    out_dir = job.output_dir
    blend = out_dir / f"{slug}.blend"
    if not blend.exists():
        return {"ok": False, "problems": [
            "build the job first - baking needs the built .blend file"]}
    exe = exe or blender_export.find_blender()
    if not exe:
        return {"ok": False, "problems": [
            "Blender is not installed, so nothing can be baked"]}
    payload = {"out": str(out_dir), "slug": slug, "res": resolution,
               "parts": [{"id": p["id"], "maps": p["maps"]}
                         for p in bakeable]}
    total_maps = sum(len(p["maps"]) for p in bakeable)
    total_maps += sum(1 for p in bakeable if p["metallic"] > 0)
    bake_skips: list[dict] = []
    landed_count = [0]

    def on_line(line: str) -> None:
        # Progress only: the landed list is read from disk after
        # the run, so a streamed line that never arrives cannot
        # make the report lie about what landed.
        if line.startswith("DS_BAKE "):
            pieces = line.split(" ", 3)
            landed_count[0] += 1
            if progress is not None:
                progress(landed_count[0] / max(1, total_maps),
                         f"baked {pieces[1]} {pieces[2]}"
                         if len(pieces) > 2 else "baked a map")
        elif line.startswith("DS_BAKE_SKIP "):
            rest = line[len("DS_BAKE_SKIP "):].strip()
            pieces = rest.split(" ", 2)
            part_id = pieces[0] if pieces else "?"
            if len(pieces) > 2 and pieces[1] in MAP_NAMES:
                # Per-map skip: "part map reason".
                reason = pieces[2]
            elif len(pieces) > 1:
                # Whole-part skip: "part reason...".
                reason = " ".join(pieces[1:])
            else:
                reason = "skipped"
            bake_skips.append({"id": part_id, "reason": reason})

    lock = governor.HeavyJobLock(workspace / ".heavy.lock")
    try:
        with lock:
            script = blender_export.generate_bake_script(payload)
            import tempfile

            with tempfile.TemporaryDirectory(
                    prefix="skullpt-bake-") as tmp:
                script_path = Path(tmp) / "bake.py"
                script_path.write_text(script)
                out = blender_export._run_blender(
                    exe, script_path, "CYCLES", timeout=timeout,
                    cancel=cancel, on_line=on_line)
    except governor.Cancelled:
        raise
    except governor.GovernorError as exc:
        # Like a build refusal: the job is untouched, the bake just
        # did not run. Say so plainly instead of failing the job.
        return {"ok": False, "stage": "governor",
                "problems": [str(exc)]}
    if "DS_BAKE_DONE" not in out:
        return {"ok": False, "problems": [
            "Blender ran but the bake did not finish - "
            + (out.strip().splitlines()[-1] if out.strip()
               else "no output from Blender")]}
    # The landed list is read from disk: a map counts only when its
    # file exists and is non-empty.
    landed = []
    for part in bakeable:
        for map_name in part["maps"]:
            name = bake_map_name(slug, part["id"], map_name)
            path = out_dir / name
            if path.exists() and path.stat().st_size > 0:
                landed.append(name)
    # Metallic maps are flat PNGs, written host-side: metallic is a
    # constant per part, so there is nothing for Blender to sample.
    for part in bakeable:
        if part["metallic"] > 0:
            name = bake_map_name(slug, part["id"], "metallic")
            write_flat_png(out_dir / name, resolution,
                           part["metallic"] * 255)
            landed.append(name)
            if progress is not None:
                progress(len(landed) / max(1, total_maps),
                         f"baked {part['id']} metallic")
    landed = sorted(set(landed))
    per_part: dict[str, list[str]] = {}
    for name in landed:
        stem = name[len(slug) + 1:-4]  # "<part>-<map>"
        part_id, map_name = stem.rsplit("-", 1)
        per_part.setdefault(part_id, []).append(map_name)
    report = {
        "resolution": resolution,
        "tier": tier,
        "maps": landed,
        "parts": per_part,
        "skipped": skipped + bake_skips,
    }
    (job.dir / "bake-report.json").write_text(
        json.dumps(report, indent=2) + "\n")
    # The build report carries the bake too, when one exists: the
    # Unreal package and the Bench both read it from there.
    build_report = job.dir / "build-report.json"
    if build_report.exists():
        try:
            data = json.loads(build_report.read_text())
            data["baked"] = report
            build_report.write_text(json.dumps(data, indent=2) + "\n")
        except (OSError, ValueError):
            pass
    detail = (f"baked {len(landed)} maps at {resolution}px"
              + (f" ({len(skipped + bake_skips)} skipped)"
                 if skipped or bake_skips else ""))
    return {"ok": True, "maps": landed, "skipped": skipped + bake_skips,
            "resolution": resolution, "tier": tier, "detail": detail}
